-- V1: Estrutura inicial do PetCareIA+
-- Tabelas core: PC_USUARIO, PC_PET, PC_CONSULTA, PC_VACINA
-- Prefixo PC_ evita colisão com tabelas de outros exercícios no mesmo schema Oracle

CREATE TABLE PC_USUARIO (
    ID            NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NOME          VARCHAR2(120) NOT NULL,
    EMAIL         VARCHAR2(150) NOT NULL,
    SENHA         VARCHAR2(255) NOT NULL,
    PERFIL        VARCHAR2(20)  NOT NULL,
    CRIADO_EM     TIMESTAMP     NOT NULL,
    CONSTRAINT UK_PC_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_PC_USUARIO_PERFIL CHECK (PERFIL IN ('TUTOR', 'CLINICA'))
);

COMMENT ON TABLE PC_USUARIO IS 'Usuários do sistema PetCareIA+: tutores e clínica (2 perfis exigidos pelo Spring Security)';

CREATE TABLE PC_PET (
    ID                NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NOME              VARCHAR2(80)  NOT NULL,
    RACA              VARCHAR2(40)  NOT NULL,
    DATA_NASCIMENTO   DATE,
    PESO              NUMBER(5,2),
    FOTO_URL          VARCHAR2(300),
    TUTOR_ID          NUMBER        NOT NULL,
    CONSTRAINT FK_PC_PET_TUTOR FOREIGN KEY (TUTOR_ID) REFERENCES PC_USUARIO(ID)
);

COMMENT ON TABLE PC_PET IS 'Pets cadastrados no PetCareIA+, cada um pertence a um tutor (PC_USUARIO)';

CREATE TABLE PC_CONSULTA (
    ID            NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PET_ID        NUMBER        NOT NULL,
    DATA_HORA     TIMESTAMP     NOT NULL,
    MOTIVO        VARCHAR2(500),
    OBSERVACOES   VARCHAR2(1000),
    STATUS        VARCHAR2(20)  NOT NULL,
    CONSTRAINT FK_PC_CONSULTA_PET FOREIGN KEY (PET_ID) REFERENCES PC_PET(ID),
    CONSTRAINT CK_PC_CONSULTA_STATUS CHECK (STATUS IN ('AGENDADA', 'REALIZADA', 'CANCELADA'))
);

COMMENT ON TABLE PC_CONSULTA IS 'Consultas agendadas/realizadas de cada pet no PetCareIA+';

CREATE TABLE PC_VACINA (
    ID                    NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PET_ID                NUMBER        NOT NULL,
    NOME                  VARCHAR2(100) NOT NULL,
    DATA_APLICACAO        DATE          NOT NULL,
    DATA_PROXIMA_DOSE     DATE,
    CONSTRAINT FK_PC_VACINA_PET FOREIGN KEY (PET_ID) REFERENCES PC_PET(ID)
);

COMMENT ON TABLE PC_VACINA IS 'Carteira de vacinação de cada pet no PetCareIA+';